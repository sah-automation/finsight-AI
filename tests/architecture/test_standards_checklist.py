@pytest.mark.architecture
class TestStandardsChecklist:
    """Automated Section 17 Standards Checklist."""

    def test_standards_checklist(self) -> None:
        """Run all checklist items and generate report."""
        results = _collect_check_results()

        # Generate the report in memory.
        report = _generate_report(results)

        # When requested, write the tracked file (used by `make ratchet`).
        if os.environ.get('UPDATE_STANDARDS_REPORT') == '1':
            _write_report(results, REPORT_PATH)
        else:
            # Compare-only: never touch the tracked file; fail loudly if stale.
            existing = REPORT_PATH.read_text(encoding='utf-8') if REPORT_PATH.exists() else ''

            # Normalize both strings for cross-environment consistency:
            # - Strip trailing whitespace from each line
            # - Remove detail lines that contain environment-specific counts
            #   (test file counts, file line counts) which can differ between
            #   local and CI due to test discovery or line-ending differences.
            def _norm(s: str) -> str:
                lines = []
                for line in s.splitlines():
                    stripped = line.rstrip()
                    # Skip detail lines with counts that vary by environment
                    if stripped.startswith('  - ') and (
                        ' lines' in stripped
                        or stripped.startswith(('  - Unit:', '  - Contract:', '  - Switch:'))
                    ):
                        continue
                    lines.append(stripped)
                return '\n'.join(lines) + '\n'

            if _norm(report) != _norm(existing):
                pytest.fail('standards_report.md is stale; run `make ratchet` to update')

        # Print summary
        print(f'\n{"=" * 60}')
        print(
            f'Standards Checklist: {results["passed"]}/{results["total"]} passed, {results["failed"]} failed, {results["skipped"]} skipped'
        )
        print(f'{"=" * 60}')

        # Fail if any check failed (not skipped)
        assert results['failed'] == 0, (
            f'Standards checklist failed: {results["failed"]} checks failed. See {REPORT_PATH}'
        )
